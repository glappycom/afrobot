function tableStatements(sqliteSql) {
  const tables = sqliteSql
    .replace(/PRAGMA[^;]*;/g, '')
    .replace(/CREATE TRIGGER[\s\S]*?END;/g, '')
    .replace(/ REFERENCES [a-z_]+\([^)]+\)/g, '')
    .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/g, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  return tables.split(';').map((part) => part.trim()).filter((part) => part.length > 0);
}

export function postgresSetup(schemaSql, ledgerSql) {
  return [...tableStatements(schemaSql), ...tableStatements(ledgerSql), ...TRIGGERS];
}

export function bindPlaceholders(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => {
    index += 1;
    return `$${index}`;
  });
}

export function numberish(value) {
  if (typeof value === 'string' && /^-?\d+$/.test(value) && value.length < 16) return Number(value);
  return value;
}

export function normalizeRow(row) {
  if (!row) return row;
  const out = {};
  for (const [key, value] of Object.entries(row)) out[key] = numberish(value);
  return out;
}
